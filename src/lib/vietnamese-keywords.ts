/**
 * Chuẩn hóa chuỗi tiếng Việt: viết thường, bỏ dấu thanh, chuyển đ -> d
 */
export function normalizeVietnamese(input: string): string {
  return input
    .toLowerCase()
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .replace(/đ/g, "d")
    .replace(/[^a-z0-9\s]/g, " ")
    .replace(/\s+/g, " ")
    .trim();
}

